/**
 * Generates `public/images/portrait.jpg` — the portrait plate used by the
 * identity strip and the channel card — plus the inline LQIP in
 * `lib/portrait.ts`.
 *
 * The committed image is a designed PLACEHOLDER, not a photograph. To use a
 * real portrait instead:
 *
 *   1. drop the photo at `public/images/portrait.jpg` (portrait crop, ~1100x1467)
 *   2. run `node scripts/generate-portrait-placeholder.mjs --from <path/to/photo>`
 *      to regenerate both the resized image and the blur placeholder.
 *
 * Run with no arguments to regenerate the placeholder plate.
 */
import { writeFileSync } from "node:fs";
import sharp from "sharp";

const W = 1100;
const H = 1467;
const OUT = "public/images/portrait.jpg";

const fromIndex = process.argv.indexOf("--from");
const source = fromIndex > -1 ? process.argv[fromIndex + 1] : null;

/** The placeholder plate: chiaroscuro ground, gold rule, monogram. */
function plateSvg() {
  const tiles = [];
  // A chessboard in steep perspective along the bottom edge — the same
  // opening image as the hero, reduced to a watermark.
  for (let row = 0; row < 5; row += 1) {
    const y = H - 300 + row * 62;
    const squash = 1 - row * 0.11;
    for (let col = 0; col < 9; col += 1) {
      if ((row + col) % 2 !== 0) continue;
      const w = 150 * squash;
      const x = W / 2 - 4.5 * w + col * w;
      tiles.push(
        `<rect x="${x.toFixed(1)}" y="${y}" width="${w.toFixed(1)}" height="${(58 * squash).toFixed(1)}" fill="#ede4d3" opacity="${(0.05 - row * 0.008).toFixed(3)}"/>`,
      );
    }
  }

  return `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}">
  <defs>
    <linearGradient id="ground" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0%" stop-color="#15151a"/>
      <stop offset="55%" stop-color="#0d0d10"/>
      <stop offset="100%" stop-color="#07070a"/>
    </linearGradient>
    <radialGradient id="key" cx="32%" cy="26%" r="62%">
      <stop offset="0%" stop-color="#c8a45c" stop-opacity="0.22"/>
      <stop offset="60%" stop-color="#c8a45c" stop-opacity="0.05"/>
      <stop offset="100%" stop-color="#c8a45c" stop-opacity="0"/>
    </radialGradient>
  </defs>

  <rect width="${W}" height="${H}" fill="url(#ground)"/>
  <rect width="${W}" height="${H}" fill="url(#key)"/>
  ${tiles.join("\n  ")}

  <rect x="26" y="26" width="${W - 52}" height="${H - 52}" fill="none"
        stroke="#c8a45c" stroke-opacity="0.28" stroke-width="1.5"/>

  <text x="${W / 2}" y="${H * 0.5}" text-anchor="middle"
        font-family="Georgia, 'Times New Roman', serif" font-size="330"
        fill="#ede4d3" fill-opacity="0.13" letter-spacing="14">SD</text>

  <text x="${W / 2}" y="${H * 0.5 + 96}" text-anchor="middle"
        font-family="'DejaVu Sans Mono', monospace" font-size="30"
        fill="#8d867a" fill-opacity="0.75" letter-spacing="14">SINA DEHESH</text>

  <text x="${W / 2}" y="${H - 74}" text-anchor="middle"
        font-family="'DejaVu Sans Mono', monospace" font-size="21"
        fill="#8d867a" fill-opacity="0.45" letter-spacing="7">PORTRAIT PLATE</text>
</svg>`;
}

const pipeline = source
  ? sharp(source)
  : sharp(Buffer.from(plateSvg()));

const image = await pipeline
  .resize(W, H, { fit: "cover", position: "top" })
  .jpeg({ quality: 84, progressive: true })
  .toBuffer();

writeFileSync(OUT, image);

const lqip = await sharp(image).resize(20).jpeg({ quality: 40 }).toBuffer();
writeFileSync(
  "lib/portrait.ts",
  `/** Tiny inline LQIP for the portrait, generated by scripts/generate-portrait-placeholder.mjs. */\nexport const portraitBlur =\n  "data:image/jpeg;base64,${lqip.toString("base64")}";\n`,
);

console.log(`wrote ${OUT} (${image.length} bytes)${source ? ` from ${source}` : " (placeholder plate)"}`);
